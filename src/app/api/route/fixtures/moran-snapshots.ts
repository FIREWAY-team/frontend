/** 모란 좌표 15m 반경 안쪽 체크 (스냅샷 적용 조건) */
export function isMoranShootDest(to: unknown): boolean {
  if (!to || typeof to !== "object") return false;
  const t = to as { lat?: unknown; lon?: unknown };
  if (typeof t.lat !== "number" || typeof t.lon !== "number") return false;
  const dy = (t.lat - MORAN_SHOOT_DEST.lat) * 111_132;
  const dx = (t.lon - MORAN_SHOOT_DEST.lon) * 88_400;
  return Math.hypot(dx, dy) < 15;
}

